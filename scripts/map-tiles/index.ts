import path from "node:path";
import { fileURLToPath } from "node:url";
import { WORLDS } from "../../shared/map/worlds";
import { buildWorldTiles, type TileSummary } from "./build";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const QUALITY = 80;
const MB = 1024 * 1024;

const describe = (summary: TileSummary): string =>
  summary.skipped ? `${summary.world}：原圖未變，略過` : `${summary.world}：${summary.tiles} 張圖塊，${(summary.bytes / MB).toFixed(1)} MB`;

async function main(): Promise<void> {
  const sourceRoot = path.resolve(process.argv[2] ?? path.join(projectRoot, "source-data"));
  const options = {
    sourceDir: path.join(sourceRoot, "Assets", "AutoGenerated", "World", "WorldMap", "BeautyRender"),
    outDir: path.join(projectRoot, "public", "map"),
    quality: QUALITY,
  };
  // One world at a time keeps memory to a single pyramid.
  const summaries: TileSummary[] = [];
  for (const world of WORLDS) summaries.push(await buildWorldTiles(world, options));
  console.log(["地圖圖塊完成：", ...summaries.map(describe)].join("\n"));
}

main().catch((error: unknown) => {
  console.error(`地圖圖塊失敗：${error instanceof Error ? error.message : String(error)}`);
  process.exitCode = 1;
});
