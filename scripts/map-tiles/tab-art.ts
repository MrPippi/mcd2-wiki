/**
 * The art around the world tabs: a pixelated crop of each world's WorldMap texture (the game paints its dimension
 * tabs with a mosaic of it) and the Z / X keycap glyphs cut from the game's keyboard sprite sheet.
 */
import { existsSync } from "node:fs";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";
import { MapTilesError } from "./build";

/** Tab picture size in pixels; the page shows it enlarged without smoothing, which is the mosaic. */
export const TAB_WIDTH = 96;
export const TAB_HEIGHT = 40;
/** The sprite sheet is a 9×9 grid of 84-pixel cells. */
export const KEY_CELL = 84;
/** Cell origins (pixels) of the keys the world tabs show; the game binds Z to the previous world and X to the next. */
export const KEY_CELLS = { z: { left: 588, top: 168 }, x: { left: 420, top: 168 } } as const;
export type KeyName = keyof typeof KEY_CELLS;

/** Pixels brighter than this (summed RGB) are land; the texture's void is black. */
const LAND_LEVEL = 12;
const QUALITY = 80;

export interface Box {
  readonly left: number;
  readonly top: number;
  readonly width: number;
  readonly height: number;
}

const isLand = (rgb: Uint8Array, offset: number): boolean => rgb[offset] + rgb[offset + 1] + rgb[offset + 2] > LAND_LEVEL;

/** The smallest box around the non-black pixels of a packed image with `channels` bytes per pixel. */
export function landBox(rgb: Uint8Array, width: number, height: number, channels = 3): Box {
  let left = width;
  let top = height;
  let right = -1;
  let bottom = -1;
  for (let y = 0; y < height; y += 1) {
    for (let x = 0; x < width; x += 1) {
      if (!isLand(rgb, (y * width + x) * channels)) continue;
      left = Math.min(left, x);
      right = Math.max(right, x);
      top = Math.min(top, y);
      bottom = Math.max(bottom, y);
    }
  }
  if (right < 0) throw new MapTilesError("世界地圖底圖沒有任何陸地像素");
  return { left, top, width: right - left + 1, height: bottom - top + 1 };
}

/** The part of `box` with the tab's aspect ratio, centred, so the crop fills the tab without stretching. */
export function tabCrop(box: Box): Box {
  const wanted = TAB_WIDTH / TAB_HEIGHT;
  const width = Math.min(box.width, Math.round(box.height * wanted));
  const height = Math.min(box.height, Math.round(box.width / wanted));
  return { left: box.left + Math.floor((box.width - width) / 2), top: box.top + Math.floor((box.height - height) / 2), width, height };
}

/** RGBA copy of packed RGB with the black void made transparent, so the tab's own background shows around the land. */
export function voidToAlpha(rgb: Uint8Array, channels = 3): Uint8Array {
  const pixels = rgb.length / channels;
  const out = new Uint8Array(pixels * 4);
  for (let p = 0; p < pixels; p += 1) {
    out.set(rgb.subarray(p * channels, p * channels + 3), p * 4);
    out[p * 4 + 3] = isLand(rgb, p * channels) ? 255 : 0;
  }
  return out;
}

async function tabImage(file: string): Promise<Buffer> {
  // Read without alpha: the texture's alpha is 0 everywhere, which would turn a resize black.
  const raw = await sharp(file).removeAlpha().raw().toBuffer({ resolveWithObject: true });
  const { width, height, channels } = raw.info;
  const crop = tabCrop(landBox(new Uint8Array(raw.data), width, height, channels));
  const rgba = voidToAlpha(new Uint8Array(raw.data), channels);
  return sharp(rgba, { raw: { width, height, channels: 4 } }).extract(crop).resize(TAB_WIDTH, TAB_HEIGHT, { kernel: "mitchell" }).webp({ quality: QUALITY }).toBuffer();
}

export interface TabArtOptions {
  /** source-data/Assets. */
  readonly assetsDir: string;
  /** public/map. */
  readonly outDir: string;
  readonly worlds: readonly { readonly key: string; readonly region: string }[];
}

const WORLD_MAP_DIR = ["AutoGenerated", "World", "WorldMap"];
const KEY_SHEET = ["Core", "Platform", "Input", "CommonUIInput", "KeyboardMouse", "T_UI_Icon_SpriteSheet_PC_Set1.png"];

function requireFile(file: string): string {
  if (!existsSync(file)) throw new MapTilesError(`缺少分頁用圖：${file}`);
  return file;
}

/** Writes tabs/<world>.webp and keys/<z|x>.png under the map folder. */
export async function buildTabArt(options: TabArtOptions): Promise<number> {
  const tabsDir = path.join(options.outDir, "tabs");
  const keysDir = path.join(options.outDir, "keys");
  await mkdir(tabsDir, { recursive: true });
  await mkdir(keysDir, { recursive: true });
  for (const world of options.worlds) {
    const file = requireFile(path.join(options.assetsDir, ...WORLD_MAP_DIR, `${world.region}WorldMap.png`));
    await writeFile(path.join(tabsDir, `${world.key}.webp`), await tabImage(file));
  }
  const sheet = requireFile(path.join(options.assetsDir, ...KEY_SHEET));
  for (const [name, cell] of Object.entries(KEY_CELLS)) {
    const png = await sharp(sheet).extract({ ...cell, width: KEY_CELL, height: KEY_CELL }).png().toBuffer();
    await writeFile(path.join(keysDir, `${name}.png`), png);
  }
  return options.worlds.length + Object.keys(KEY_CELLS).length;
}
